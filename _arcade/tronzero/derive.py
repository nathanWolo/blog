"""Derive the arcade engine's sources from the upstream tronzero engine.

Reads engine/src/{board,net,mcts,play}.rs and paste/net_packed.txt from a
tron-codingame checkout and writes src/upstream/{board,net,mcts,play}.rs and
net_packed.txt next to this script. Every edit is an exact-text substitution
that must match the expected number of times, so a change upstream fails loudly
here instead of producing a wrong port.

usage: derive.py <path to the upstream checkout> [commit]
       (the commit defaults to `git rev-parse HEAD` of the checkout)
"""
import shutil
import subprocess
import sys
from pathlib import Path

REPO = "github.com/nathanWolo/tron-codingame"
here = Path(__file__).resolve().parent
root = Path(sys.argv[1])
commit = sys.argv[2] if len(sys.argv) > 2 else subprocess.run(
    ["git", "-C", str(root), "rev-parse", "HEAD"], capture_output=True, text=True, check=True
).stdout.strip()

X86 = '#[cfg(target_arch = "x86_64")]'


class Source:
    def __init__(self, name):
        self.name = name
        # Upstream is checked out with CRLF on Windows; the output is always LF.
        self.s = (root / "engine" / "src" / f"{name}.rs").read_text(encoding="utf-8").replace("\r\n", "\n")

    def swap(self, old, new, count=1):
        found = self.s.count(old)
        assert found == count, f"{self.name}.rs: expected {count} of {old!r}, found {found}"
        self.s = self.s.replace(old, new)

    def cut_to_end(self, start):
        assert self.s.count(start) == 1, f"{self.name}.rs: expected one {start!r}"
        self.s = self.s[: self.s.index(start)].rstrip("\n") + "\n"

    def write(self):
        header = (
            f"// Derived from {REPO} at commit {commit}\n"
            f"// (engine/src/{self.name}.rs). Generated by derive.py; do not edit by hand.\n"
        )
        (here / "src" / "upstream" / f"{self.name}.rs").write_text(header + self.s, encoding="utf-8", newline="\n")


src = {n: Source(n) for n in ("board", "net", "mcts", "play")}

# --- net.rs: the AVX2/FMA kernels exist on x86_64 only; everything else runs the scalar path.
net = src["net"]
# 1. the intrinsics import
net.swap("use std::arch::x86_64::*;\n", f"{X86}\nuse std::arch::x86_64::*;\n")
# 2. the three #[target_feature] kernels: conv_nv, conv_planes, dense_nv
net.swap('#[target_feature(enable = "avx2,fma")]\n', f'{X86}\n#[target_feature(enable = "avx2,fma")]\n', 3)
# 3. conv_bbox's dispatch into conv_nv
net.swap("    unsafe {\n        match cout / 8 {", f"    {X86}\n    unsafe {{\n        match cout / 8 {{")
# 4. dense_bbox's dispatch into dense_nv
net.swap("    unsafe {\n        match n / 8 {", f"    {X86}\n    unsafe {{\n        match n / 8 {{")
# 5. eval's call of conv_planes for the first layer
net.swap("            if l == 0 && cout == 16 && self.simd {", f"            {X86}\n            if l == 0 && cout == 16 && self.simd {{")
# 6. run-time CPU detection and the TZ_SCALAR switch (x86_64 only; elsewhere simd is false)
net.swap(
    '        let simd = is_x86_feature_detected!("avx2")\n'
    '            && is_x86_feature_detected!("fma")\n'
    '            && std::env::var_os("TZ_SCALAR").is_none();\n',
    f'        {X86}\n'
    '        let simd = is_x86_feature_detected!("avx2")\n'
    '            && is_x86_feature_detected!("fma")\n'
    '            && std::env::var_os("TZ_SCALAR").is_none();\n'
    '        #[cfg(not(target_arch = "x86_64"))]\n'
    '        let simd = false;\n',
)

# --- play.rs: the CodinGame stdin loop and its settings need main.rs's budgets and a process.
play = src["play"]
# 7. its imports
play.swap("use std::io::{BufRead, Write};\n", "")
# 8. `setting` and `run`, the rest of the file
play.cut_to_end("/// A setting from `--name value` on the command line")

for s in src.values():
    s.write()

shutil.copyfile(root / "paste" / "net_packed.txt", here / "net_packed.txt")
print(f"derived board, net, mcts, play and net_packed.txt from {root} at {commit}")
